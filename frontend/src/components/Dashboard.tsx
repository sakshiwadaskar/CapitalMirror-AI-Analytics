import type { FinancialData, Assumptions, HealthScore, BusinessInsights } from '../types'
import { ScorePanel } from './ScorePanel'
import { MetricCards } from './MetricCards'
import { Charts } from './Charts'
import { InsightsPanel } from './InsightsPanel'

function buildMailto(data: FinancialData, healthScore: HealthScore, insights: BusinessInsights): string {
  const name = data.business_name ?? 'Business'
  const fy = data.fiscal_year ? ` (FY ${data.fiscal_year})` : ''
  const m = healthScore.metrics
  const fmt = (n: number) => Math.abs(n) >= 1_000_000 ? `$${(n/1_000_000).toFixed(2)}M` : Math.abs(n) >= 1_000 ? `$${(n/1_000).toFixed(0)}K` : `$${n.toFixed(0)}`
  const pct = (n: number) => `${n > 0 ? '+' : ''}${(n * 100).toFixed(1)}%`

  const subject = `Business Health Report — ${name}`
  const body = [
    `BUSINESS HEALTH REPORT — ${name.toUpperCase()}${fy}`,
    '='.repeat(50),
    '',
    `Health Score: ${Math.round(healthScore.score)}/100`,
    '',
    'KEY METRICS',
    `-----------`,
    `Revenue:       ${fmt(m.revenue)}`,
    `Gross Margin:  ${pct(m.gross_margin_pct)}`,
    `Owner SDE:     ${fmt(m.sde)} (${pct(m.sde_ratio)} of revenue)`,
    `Monthly Burn:  ${fmt(m.monthly_burn)}/mo`,
    `YoY Growth:    ${pct(m.yoy_growth)}`,
    `Expense Ratio: ${pct(m.expense_ratio)} (OpEx/Gross Profit)`,
    '',
    ...(insights.fix_first.length ? ['TOP PRIORITIES', '--------------', ...insights.fix_first.map((s, i) => `${i + 1}. ${s}`), ''] : []),
    ...(insights.whats_working.length ? ["WHAT'S WORKING", '--------------', ...insights.whats_working.map(s => `• ${s}`), ''] : []),
    'Generated by Business Health Dashboard',
  ].join('\n')

  return `mailto:?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`
}

interface Props {
  data: FinancialData
  assumptions: Assumptions
  onAssumptionsChange: (a: Assumptions) => void
  healthScore: HealthScore
  rationale: string
  insights: BusinessInsights
  rationaleLoading: boolean
  rationaleError: boolean
  onReset: () => void
}

export function Dashboard({
  data, assumptions, onAssumptionsChange,
  healthScore, rationale, insights, rationaleLoading, rationaleError, onReset,
}: Props) {
  return (
    <div className="max-w-5xl mx-auto">
      <div className="mb-6 pb-4" style={{ borderBottom: '1px solid var(--ct-border)' }}>
        <p className="text-xs font-semibold uppercase tracking-widest text-slate-600 cursor-default">
          Business Health Dashboard
        </p>
      </div>

      <div className="flex items-center justify-between mb-6">
        <div>
          <h1 className="text-2xl font-bold text-white">{data.business_name ?? 'Business Health Dashboard'}</h1>
          {data.fiscal_year && <p className="text-slate-500 text-sm mt-0.5">FY {data.fiscal_year}</p>}
        </div>
        <div className="flex items-center gap-3">
          <a
            href={buildMailto(data, healthScore, insights)}
            className="text-sm font-semibold text-white px-4 py-2 rounded-lg transition-colors inline-block"
            style={{ backgroundColor: 'var(--ct-black)', border: '1px solid var(--ct-border)' }}
            onMouseEnter={e => {
              (e.currentTarget as HTMLAnchorElement).style.backgroundColor = 'var(--ct-maroon)'
              ;(e.currentTarget as HTMLAnchorElement).style.borderColor = 'var(--ct-maroon)'
            }}
            onMouseLeave={e => {
              (e.currentTarget as HTMLAnchorElement).style.backgroundColor = 'var(--ct-black)'
              ;(e.currentTarget as HTMLAnchorElement).style.borderColor = 'var(--ct-border)'
            }}
          >
            ✉ Email Report
          </a>
          <button
            className="text-sm font-semibold text-white px-4 py-2 rounded-lg transition-colors"
            style={{ backgroundColor: 'var(--ct-black)', border: '1px solid var(--ct-border)' }}
            onMouseEnter={e => {
              e.currentTarget.style.backgroundColor = 'var(--ct-maroon)'
              e.currentTarget.style.borderColor = 'var(--ct-maroon)'
            }}
            onMouseLeave={e => {
              e.currentTarget.style.backgroundColor = 'var(--ct-black)'
              e.currentTarget.style.borderColor = 'var(--ct-border)'
            }}
            onClick={onReset}
          >
            ← New Analysis
          </button>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        <div className="lg:col-span-1">
          <ScorePanel
            healthScore={healthScore}
            assumptions={assumptions}
            onAssumptionsChange={onAssumptionsChange}
            rationale={rationale}
            rationaleLoading={rationaleLoading}
          />
        </div>

        <div className="lg:col-span-2 space-y-6">
          <InsightsPanel insights={insights} loading={rationaleLoading} error={rationaleError} />
          <MetricCards metrics={healthScore.metrics} hasGrowthAssumption={assumptions.growth_rate !== 0} industry={data.industry ?? null} />
          <Charts metrics={healthScore.metrics} />
          {data.notes && (
            <div
              className="group rounded-xl p-4 border border-t-2"
              style={{ backgroundColor: 'var(--ct-card)', borderColor: 'var(--ct-border)', borderTopColor: 'var(--ct-maroon)' }}
            >
              <div className="text-xs font-semibold uppercase tracking-widest mb-2 text-slate-500 group-hover:text-red-900 transition-colors">
                Notes
              </div>
              <p className="text-slate-300 text-sm leading-relaxed">{data.notes}</p>
            </div>
          )}
        </div>
      </div>
    </div>
  )
}
